def split_frontmatter(text: str, where: str) -> tuple[dict, str]:
    if not text.startswith("+++\n"):
        raise SyncError(f"{where}: must begin with a +++ TOML frontmatter block")
    end = text.find("\n+++\n", 3)
    if end < 0:
        raise SyncError(f"{where}: frontmatter is not closed with +++")
    try:
        meta = tomllib.loads(text[4:end + 1])
    except tomllib.TOMLDecodeError as error:
        raise SyncError(f"{where}: invalid frontmatter ({error})") from error
    return meta, text[end + 5:].lstrip("\n")


def render(text: str, context: dict, tool: str | None, where: str) -> str:
    for pattern in (BLOCK_SECTION_RE, INLINE_SECTION_RE):
        text = pattern.sub(lambda m: m.group(2) if m.group(1) == tool else "", text)
    if "{{#" in text or "{{/" in text:
        raise SyncError(f"{where}: unbalanced or nested {{{{#tool}}}} section")

    def substitute(match: re.Match) -> str:
        value = context
        for part in match.group(1).split("."):
            if not isinstance(value, dict) or part not in value:
                line = text.count("\n", 0, match.start()) + 1
                raise SyncError(f"{where}:{line}: unknown template variable {{{{{match.group(1)}}}}}")
            value = value[part]
        if isinstance(value, (dict, list)):
            raise SyncError(f"{where}: template variable {{{{{match.group(1)}}}}} is not a scalar")
        return str(value)

    return VAR_RE.sub(substitute, text)


@dataclass
class Component:
    kind: str  # "agent" or "skill"
    name: str
    origin: str  # "template" or "local"
    source: Path  # agent: the .md file; skill: the directory
    meta: dict
    body: str

    @property
    def label(self) -> str:
        return f"{self.kind} {self.name}"


def load_component(kind: str, name: str, origin: str, source: Path) -> Component:
    entry = source if kind == "agent" else source / "SKILL.md"
    if not entry.is_file():
        raise SyncError(f"{entry}: missing")
    meta, body = split_frontmatter(entry.read_text(encoding="utf-8"), str(entry))
    allowed = AGENT_KEYS if kind == "agent" else SKILL_KEYS
    unknown = set(meta) - allowed
    if unknown:
        raise SyncError(f"{entry}: unknown frontmatter keys {sorted(unknown)}")
    for tool in TOOLS:
        if tool in meta and not isinstance(meta[tool], dict):
            raise SyncError(f"{entry}: [{tool}] must be a table")
    if meta.get("name") != name:
        raise SyncError(f"{entry}: frontmatter name {meta.get('name')!r} does not match {name!r}")
    if not NAME_RE.match(name) or len(name) > 64:
        raise SyncError(f"{entry}: name {name!r} must be lowercase words joined by hyphens, at most 64 characters")
    if kind == "agent":
        stage = meta.get("stage")
        if not isinstance(stage, str) or not stage.strip():
            raise SyncError(f"{entry}: stage is required")
        assigned = meta.get("skills", [])
        if not isinstance(assigned, list) or any(not isinstance(item, str) for item in assigned):
            raise SyncError(f"{entry}: skills must be an array of skill names")
        if len(assigned) != len(set(assigned)):
            raise SyncError(f"{entry}: skills contains a duplicate")
        for skill_name in assigned:
            if not NAME_RE.match(skill_name):
                raise SyncError(f"{entry}: invalid skill name {skill_name!r}")
    description = meta.get("description")
    if not isinstance(description, str) or not description.strip():
        raise SyncError(f"{entry}: description is required")
    if len(description) > 1024:
        raise SyncError(f"{entry}: description is {len(description)} characters; the limit is 1024")
    if "\n" in description:
        raise SyncError(f"{entry}: description must be one line")
    summary = meta.get("summary", "")
    if not isinstance(summary, str) or not summary.strip() or len(summary) > 100 or "\n" in summary:
        raise SyncError(f"{entry}: summary is required and must be one line of at most 100 characters")
    if origin == "local":
        unfinished = [description, summary, meta.get("stage", ""), body.lstrip()]
        if any(isinstance(value, str) and value.startswith(("TODO:", "# TODO:")) for value in unfinished):
            raise SyncError(f"{entry}: finish the scaffold TODOs before syncing")
    return Component(kind, name, origin, source, meta, body)


@dataclass
class Templates:
    root: Path
    manifest: dict
    agents: list[Component]
    skills: list[Component]
    orchestrator: str
    partials: dict[str, str]

    @property
    def version(self) -> str:
        return self.manifest["system"]["version"]

    @property
    def engine(self) -> Path:
        return self.root / self.manifest["system"]["engine"]


def load_templates(root: Path) -> Templates:
    root = root.resolve()
    manifest = read_toml(root / "manifest.toml")
    unknown = set(manifest) - MANIFEST_KEYS
    if unknown:
        raise SyncError(f"manifest.toml: unknown tables or keys {sorted(unknown)}")

    system = require_mapping(manifest.get("system"), "manifest.toml [system]")
    if manifest.get("schema") != 1 or system.get("name") != SYSTEM:
        raise SyncError(f"{root / 'manifest.toml'}: not a schema 1 {SYSTEM} manifest")
    if not isinstance(system.get("version"), str) or not system["version"].strip():
        raise SyncError("manifest.toml: [system] version must be a non-empty string")
    engine_path = template_source(root, system.get("engine"), "manifest.toml [system]")
    if not engine_path.is_file():
        raise SyncError(f"{engine_path}: missing engine")

    defaults = require_mapping(manifest.get("defaults", {}), "manifest.toml [defaults]")
    unknown_defaults = set(defaults) - {"project", "commands"}
    if unknown_defaults:
        raise SyncError(f"manifest.toml: [defaults] has unknown tables {sorted(unknown_defaults)}")
    for table in ("project", "commands"):
        values = require_mapping(defaults.get(table, {}), f"manifest.toml [defaults.{table}]")
        for key, value in values.items():
            if not CONTEXT_KEY_RE.match(key) or not isinstance(value, str):
                raise SyncError(f"manifest.toml: [defaults.{table}] {key!r} must be a string with a template-safe key")

    tools = require_mapping(manifest.get("tools"), "manifest.toml [tools]")
    unknown_tools = set(tools) - set(TOOLS)
    if unknown_tools:
        raise SyncError(f"manifest.toml: unsupported tools {sorted(unknown_tools)}")
    required_tool_keys = {"name", "instructions", "agents_dir", "skills_dir", "hook_file", "skill_prefix"}
    for tool in TOOLS:
        definition = require_mapping(tools.get(tool), f"manifest.toml [tools.{tool}]")
        missing = required_tool_keys - set(definition)
        if missing:
            raise SyncError(f"manifest.toml: [tools.{tool}] is missing {sorted(missing)}")
        for key in required_tool_keys:
            if not isinstance(definition[key], str) or not definition[key]:
                raise SyncError(f"manifest.toml: [tools.{tool}] {key} must be a non-empty string")
        for key in ("instructions", "agents_dir", "skills_dir", "hook_file"):
            inside(root, definition[key])
        limit = definition.get("instructions_max_bytes")
        if limit is not None and (not isinstance(limit, int) or isinstance(limit, bool) or limit <= 0):
            raise SyncError(f"manifest.toml: [tools.{tool}] instructions_max_bytes must be a positive integer")

    agents, skills, seen = [], [], set()
    for kind, key in (("agent", "agents"), ("skill", "skills")):
        entries = require_list(manifest.get(key, []), f"manifest.toml [[{key}]]")
        for index, item in enumerate(entries, 1):
            entry = require_mapping(item, f"manifest.toml [[{key}]] {index}")
            extra = set(entry) - {"name", "source"}
            if extra:
                raise SyncError(f"manifest.toml: [[{key}]] {index} has unknown keys {sorted(extra)}")
            name = entry.get("name", "")
            if (kind, name) in seen:
                raise SyncError(f"manifest.toml: {kind} {name!r} is listed twice")
            seen.add((kind, name))
            source = template_source(root, entry.get("source"), f"manifest.toml [[{key}]] {index}")
            component = load_component(kind, name, "template", source)
            (agents if kind == "agent" else skills).append(component)

    orchestrator = require_mapping(manifest.get("orchestrator"), "manifest.toml [orchestrator]")
    if set(orchestrator) != {"source"}:
        raise SyncError("manifest.toml: [orchestrator] must contain only source")
    orchestrator_path = template_source(root, orchestrator["source"], "manifest.toml [orchestrator]")
    if not orchestrator_path.is_file():
        raise SyncError(f"{orchestrator_path}: missing")

    partials = {}
    for key, relative in require_mapping(manifest.get("partials", {}), "manifest.toml [partials]").items():
        if not CONTEXT_KEY_RE.match(key):
            raise SyncError(f"manifest.toml: partial key {key!r} is not template-safe")
        path = template_source(root, relative, f"manifest.toml [partials] {key}")
        if not path.is_file():
            raise SyncError(f"{path}: missing partial {key!r}")
        partials[key] = path.read_text(encoding="utf-8")
    for table in ("seeds", "managed"):
        mapping = require_mapping(manifest.get(table, {}), f"manifest.toml [{table}]")
        for target, relative in mapping.items():
            inside(root, target)
            path = template_source(root, relative, f"manifest.toml [{table}] {target}")
            if not path.is_file():
                raise SyncError(f"manifest.toml [{table}] {target}: source {relative} is missing")
    return Templates(root, manifest, agents, skills, orchestrator_path.read_text(encoding="utf-8"), partials)


def is_templates_root(path: Path) -> bool:
    try:
        manifest = tomllib.loads((path / "manifest.toml").read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError):
        return False
    return manifest.get("system", {}).get("name") == SYSTEM


def find_templates(project: Path, lock: dict | None) -> Path | None:
    candidates = []
    if os.environ.get(TEMPLATES_ENV):
        candidates.append(Path(os.environ[TEMPLATES_ENV]))
    own = Path(__file__).resolve().parent.parent
    candidates.append(own)
    if lock and lock.get("source"):
        candidates.append(project / lock["source"])
    candidates.extend(directory / "templates" for directory in (project, *project.parents))
    for candidate in candidates:
        if is_templates_root(candidate):
            return candidate.resolve()
    return None


