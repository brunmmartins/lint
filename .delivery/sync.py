@dataclass
class Config:
    raw: dict
    project: dict
    tools: list[str]
    mode: str
    commands: dict
    variables: dict
    agents: dict
    skills: dict
    routes: list[dict]


def load_config(project: Path, templates: Templates) -> Config:
    path = project / CONFIG_REL
    if path.exists() and not path.is_file():
        raise SyncError(f"{CONFIG_REL}: expected a file")
    raw = read_toml(path) if path.is_file() else {}
    unknown = set(raw) - CONFIG_KEYS
    if unknown:
        raise SyncError(f"{CONFIG_REL}: unknown tables or keys {sorted(unknown)}")
    if raw and raw.get("schema") != 1:
        raise SyncError(f"{CONFIG_REL}: schema must be 1")

    defaults = templates.manifest.get("defaults", {})
    tables = {}
    for table in ("project", "commands", "vars", "agents", "skills"):
        tables[table] = require_mapping(raw.get(table, {}), f"{CONFIG_REL}: [{table}]")
    sync = require_mapping(raw.get("sync", {}), f"{CONFIG_REL}: [sync]")
    unknown_sync = set(sync) - SYNC_KEYS
    if unknown_sync:
        raise SyncError(f"{CONFIG_REL}: [sync] has unknown keys {sorted(unknown_sync)}")

    tools = require_list(sync.get("tools", list(TOOLS)), f"{CONFIG_REL}: [sync] tools")
    if (not tools or any(not isinstance(tool, str) or tool not in TOOLS for tool in tools)
            or len(tools) != len(set(tools))):
        raise SyncError(f"{CONFIG_REL}: [sync] tools must be a non-empty, duplicate-free subset of {list(TOOLS)}")
    mode = sync.get("mode", "auto")
    if mode not in ("auto", "pinned"):
        raise SyncError(f"{CONFIG_REL}: [sync] mode must be 'auto' or 'pinned'")

    for table in ("project", "commands", "vars"):
        for key, value in tables[table].items():
            if not CONTEXT_KEY_RE.match(key):
                raise SyncError(f"{CONFIG_REL}: [{table}] key {key!r} is not usable in a template variable")
            if not isinstance(value, str):
                raise SyncError(f"{CONFIG_REL}: [{table}] {key} must be a string")
            if table != "vars" and not value.strip():
                raise SyncError(f"{CONFIG_REL}: [{table}] {key} must not be empty")

    for kind, overrides, allowed in (
        ("agent", tables["agents"], AGENT_OVERRIDE_KEYS),
        ("skill", tables["skills"], SKILL_OVERRIDE_KEYS),
    ):
        for name, value in overrides.items():
            if not NAME_RE.match(name):
                raise SyncError(f"{CONFIG_REL}: invalid {kind} name {name!r}")
            override = require_mapping(value, f"{CONFIG_REL}: [{kind}s.{name}]")
            extra = set(override) - allowed
            if extra:
                raise SyncError(f"{CONFIG_REL}: [{kind}s.{name}] has unknown keys {sorted(extra)}")
            if "enabled" in override and not isinstance(override["enabled"], bool):
                raise SyncError(f"{CONFIG_REL}: [{kind}s.{name}] enabled must be a boolean")
            for tool in TOOLS:
                if tool in override:
                    require_mapping(override[tool], f"{CONFIG_REL}: [{kind}s.{name}.{tool}]")
            if kind == "agent" and "extra_skills" in override:
                assigned = require_list(override["extra_skills"], f"{CONFIG_REL}: [agents.{name}] extra_skills")
                if (any(not isinstance(item, str) or not NAME_RE.match(item) for item in assigned)
                        or len(assigned) != len(set(assigned))):
                    raise SyncError(
                        f"{CONFIG_REL}: [agents.{name}] extra_skills must contain unique skill names"
                    )

    routes = require_list(raw.get("routes", []), f"{CONFIG_REL}: [[routes]]")
    for index, value in enumerate(routes, 1):
        route = require_mapping(value, f"{CONFIG_REL}: route {index}")
        missing, extra = ROUTE_KEYS - set(route), set(route) - ROUTE_KEYS
        if missing:
            raise SyncError(f"{CONFIG_REL}: route {index} is missing {sorted(missing)}")
        if extra:
            raise SyncError(f"{CONFIG_REL}: route {index} has unknown keys {sorted(extra)}")
        for key in ROUTE_KEYS:
            if not isinstance(route[key], str) or not route[key].strip():
                raise SyncError(f"{CONFIG_REL}: route {index} {key} must be a non-empty string")

    project_vars = {**defaults.get("project", {}), **tables["project"]}
    commands = {**defaults.get("commands", {}), **tables["commands"]}
    return Config(raw, project_vars, tools, mode, commands, tables["vars"], tables["agents"],
                  tables["skills"], routes)


def load_local_components(project: Path) -> tuple[list[Component], list[Component]]:
    agents, skills = [], []
    agent_dir, skill_dir = project / LOCAL_REL / "agents", project / LOCAL_REL / "skills"
    if agent_dir.is_dir():
        for path in sorted(agent_dir.glob("*.md")):
            agents.append(load_component("agent", path.stem, "local", path))
    if skill_dir.is_dir():
        for path in sorted(p for p in skill_dir.iterdir() if p.is_dir() and p.name not in IGNORED_NAMES):
            skills.append(load_component("skill", path.name, "local", path))
    return agents, skills


def select_components(templates: Templates, config: Config, project: Path) -> tuple[list[Component], list[Component]]:
    local_agents, local_skills = load_local_components(project)
    selected = []
    for kind, base, local, overrides in (
        ("agent", templates.agents, local_agents, config.agents),
        ("skill", templates.skills, local_skills, config.skills),
    ):
        names = {component.name for component in base}
        for name, override in overrides.items():
            if name not in names and name not in {component.name for component in local}:
                raise SyncError(f"{CONFIG_REL}: [{kind}s.{name}] names no {kind}")
            extra = set(override) - {"enabled", "extra_skills", "claude", "codex"}
            if extra:
                raise SyncError(f"{CONFIG_REL}: [{kind}s.{name}] has unknown keys {sorted(extra)}")
        enabled = [c for c in base if overrides.get(c.name, {}).get("enabled", True)]
        enabled_names = {c.name for c in enabled}
        for component in local:
            if component.name in enabled_names:
                raise SyncError(
                    f"{LOCAL_REL}/{kind}s/{component.name}: collides with the template {kind}; "
                    f"disable the template one in {CONFIG_REL} first"
                )
        selected.append(enabled + local)
    agents, skills = selected
    skill_names = {skill.name for skill in skills}
    for agent in agents:
        for skill in agent_skill_names(agent, config):
            if skill not in skill_names:
                raise SyncError(f"agent {agent.name} needs skill {skill!r}, which is disabled or missing")
    agent_names = {agent.name for agent in agents}
    for route in config.routes:
        if route["agent"] not in agent_names:
            raise SyncError(f"{CONFIG_REL}: route agent {route['agent']!r} is disabled or missing")
    for kind, components in (("agents", agents), ("skills", skills)):
        folder = project / EXTENSIONS_REL / kind
        known = {c.name for c in components if c.origin == "template"}
        if folder.is_dir():
            for path in sorted(folder.glob("*.md")):
                if path.stem not in known:
                    raise SyncError(
                        f"{EXTENSIONS_REL}/{kind}/{path.name}: names no enabled template {kind[:-1]} "
                        f"(edit a project-local {kind[:-1]} directly in {LOCAL_REL}/{kind}/)"
                    )
    return agents, skills


def agent_skill_names(agent: Component, config: Config) -> list[str]:
    names = list(agent.meta.get("skills", []))
    for extra in config.agents.get(agent.name, {}).get("extra_skills", []):
        if extra not in names:
            names.append(extra)
    return names


def tool_meta(component: Component, config: Config, tool: str) -> dict:
    overrides = (config.agents if component.kind == "agent" else config.skills).get(component.name, {})
    return {**component.meta.get(tool, {}), **overrides.get(tool, {})}


