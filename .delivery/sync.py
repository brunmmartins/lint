@dataclass
class Plan:
    files: dict[str, bytes] = field(default_factory=dict)  # fully managed files
    blocks: dict[str, str] = field(default_factory=dict)  # managed blocks inside instruction files
    hooks: dict[str, str] = field(default_factory=dict)  # hook file -> tool
    warnings: list[str] = field(default_factory=list)


def base_context(templates: Templates, config: Config, tool: str | None) -> dict:
    tool_def = templates.manifest["tools"].get(tool, {}) if tool else {}
    context = {
        "system": {"name": SYSTEM, "version": templates.version},
        "tool": {"id": tool or "none", **{k: v for k, v in tool_def.items() if not isinstance(v, (dict, list))}},
        "project": config.project,
        "commands": config.commands,
        "vars": config.variables,
    }
    context["partials"] = {}
    for key, text in templates.partials.items():
        context["partials"][key] = render(text, context, tool, f"partial {key}").strip("\n")
    return context


def extension_text(project: Path, relative: str, context: dict, tool: str) -> str:
    path = project / relative
    if not path.is_file():
        return ""
    body = render(path.read_text(encoding="utf-8"), context, tool, relative).strip()
    if not body:
        return ""
    return (
        "## Project-specific additions\n\n"
        f"Maintained in `{relative}`. They add to the baseline above or tighten it. "
        "An exception to a K policy needs an ADR (P §1.1).\n\n"
        f"{body}\n"
    )


def with_extensions(body: str) -> str:
    if "{{project_extensions}}" in body:
        return body
    return body.rstrip("\n") + "\n\n{{project_extensions}}\n"


def roster_text(component: Component) -> str:
    """The one-line summary, or the description's first sentence when a component has no summary."""
    if component.meta.get("summary"):
        return component.meta["summary"]
    description = component.meta["description"].strip()
    return re.split(r"(?<=[.!?])\s", description, maxsplit=1)[0]


def skill_roster(skills: list[Component], context: dict, tool: str) -> str:
    prefix = context["tool"]["skill_prefix"]
    rows = ["| Skill | Use it for |", "|---|---|"]
    for skill in skills:
        marker = " (project)" if skill.origin == "local" else ""
        text = render(roster_text(skill), context, tool, skill.label)
        rows.append(f"| `{prefix}{skill.name}`{marker} | {md_cell(text)} |")
    return "\n".join(rows)


def agent_roster(agents: list[Component], context: dict, tool: str) -> str:
    rows = ["| Agent | Stage | Use it for |", "|---|---|---|"]
    for agent in agents:
        marker = " (project)" if agent.origin == "local" else ""
        text = render(roster_text(agent), context, tool, agent.label)
        rows.append(f"| `{agent.name}`{marker} | {md_cell(agent.meta.get('stage', ''))} | {md_cell(text)} |")
    return "\n".join(rows)


def routes_table(config: Config, context: dict, tool: str) -> str:
    if not config.routes:
        return f"None configured. Add `[[routes]]` entries to `{CONFIG_REL}` to insert project-specific stages."
    rows = ["| When | Dispatch | After | Gate |", "|---|---|---|---|"]
    for index, route in enumerate(config.routes, 1):
        cell = {key: md_cell(render(str(route[key]), context, tool, f"{CONFIG_REL} route {index}"))
                for key in ("trigger", "agent", "after", "gate")}
        rows.append(f"| {cell['trigger']} | `{cell['agent']}` | {cell['after']} | {cell['gate']} |")
    return "\n".join(rows)


def agent_skills_text(agent: Component, config: Config, context: dict, tool: str) -> str:
    names = agent_skill_names(agent, config)
    if not names:
        return "No skills are assigned to this agent."
    if tool == "claude":
        listed = ", ".join(f"`{name}`" for name in names)
        return f"These skills are preloaded into your context. Follow them: {listed}."
    skills_dir = context["tool"]["skills_dir"]
    lines = ["Before you start, read each of these skills and follow it:", ""]
    lines.extend(f"- `{skills_dir}/{name}/SKILL.md`" for name in names)
    return "\n".join(lines)


def build_plan(project: Path, templates: Templates, config: Config) -> Plan:
    plan = Plan()
    agents, skills = select_components(templates, config, project)
    for target, relative in templates.manifest.get("managed", {}).items():
        inside(project, target)
        plan.files[target] = (templates.root / relative).read_bytes()  # copied verbatim, never rendered
    plan.files[ENGINE_REL] = templates.engine.read_bytes()

    for tool in config.tools:
        tool_def = templates.manifest["tools"][tool]
        context = base_context(templates, config, tool)
        context["roster"] = agent_roster(agents, context, tool)
        context["skill_roster"] = skill_roster(skills, context, tool)
        context["project_routes"] = routes_table(config, context, tool)
        context["project_extensions"] = extension_text(project, f"{EXTENSIONS_REL}/orchestrator.md", context, tool)
        block = render(with_extensions(templates.orchestrator), context, tool, "orchestrator")
        block = normalize_text(block)
        limit = tool_def.get("instructions_max_bytes")
        if limit and len(block.encode()) > limit * 0.6:
            plan.warnings.append(
                f"{tool_def['instructions']}: the orchestrator block is {len(block.encode())} bytes; "
                f"{tool_def['name']} reads at most {limit} bytes of project instructions"
            )
        plan.blocks[tool_def["instructions"]] = block
        plan.hooks[tool_def["hook_file"]] = tool

        for agent in agents:
            ext_rel = f"{EXTENSIONS_REL}/agents/{agent.name}.md"
            agent_context = {
                **context,
                "component": {"name": agent.name},
                "agent_skills": agent_skills_text(agent, config, context, tool),
                "project_extensions": extension_text(project, ext_rel, context, tool) if agent.origin == "template" else "",
            }
            body = normalize_text(render(with_extensions(agent.body), agent_context, tool, str(agent.source)))
            description = render(agent.meta["description"], context, tool, agent.label).strip()
            meta = tool_meta(agent, config, tool)
            note = f"{GENERATED_NOTE}; extend it in {ext_rel}."
            if tool == "claude":
                plan.files[f"{tool_def['agents_dir']}/{agent.name}.md"] = render_claude_agent(
                    agent, description, meta, agent_skill_names(agent, config), body, note, plan
                ).encode()
            else:
                plan.files[f"{tool_def['agents_dir']}/{agent.name}.toml"] = render_codex_agent(
                    agent, description, meta, body, note, plan
                ).encode()

        for skill in skills:
            ext_rel = f"{EXTENSIONS_REL}/skills/{skill.name}.md"
            skill_context = {
                **context,
                "component": {"name": skill.name},
                "project_extensions": extension_text(project, ext_rel, context, tool) if skill.origin == "template" else "",
            }
            base = f"{tool_def['skills_dir']}/{skill.name}"
            description = render(skill.meta["description"], context, tool, skill.label).strip()
            body = normalize_text(render(with_extensions(skill.body), skill_context, tool, str(skill.source / "SKILL.md")))
            meta = tool_meta(skill, config, tool)
            note = f"<!-- {GENERATED_NOTE}; extend it in {ext_rel}. -->"
            if tool == "claude":
                if re.search(r"\$(?:[0-9]|ARGUMENTS\b)", body) and "arguments" not in meta and "argument-hint" not in meta:
                    plan.warnings.append(f"{base}/SKILL.md: '$<digit>' or $ARGUMENTS is substituted by Claude Code")
                plan.files[f"{base}/SKILL.md"] = render_claude_skill(skill, description, meta, body, note, plan).encode()
            else:
                plan.files[f"{base}/SKILL.md"], openai_yaml = render_codex_skill(skill, description, meta, body, note, plan)
                if openai_yaml:
                    plan.files[f"{base}/agents/openai.yaml"] = openai_yaml
            for support in sorted(skill.source.rglob("*")):
                relative = support.relative_to(skill.source)
                if support.is_dir() or support.is_symlink() or relative.as_posix() == "SKILL.md":
                    continue
                if IGNORED_NAMES.intersection(relative.parts) or support.suffix == ".pyc":
                    continue
                if support.suffix == ".md":
                    text = render(support.read_text(encoding="utf-8"), skill_context, tool, str(support))
                    plan.files[f"{base}/{relative.as_posix()}"] = normalize_text(text).encode()
                else:
                    plan.files[f"{base}/{relative.as_posix()}"] = support.read_bytes()

    for relative in (*plan.files, *plan.blocks, *plan.hooks):
        inside(project, relative)
    return plan


def unknown_keys(component: Component, meta: dict, allowed: tuple, tool: str, plan: Plan) -> None:
    unknown = sorted(set(meta) - set(allowed))
    if unknown:
        plan.warnings.append(f"{component.label}: ignored {tool} keys {unknown}")


def render_claude_agent(agent, description, meta, skills, body, note, plan) -> str:
    unknown_keys(agent, meta, CLAUDE_AGENT_KEYS, "claude", plan)
    front = {"name": agent.name, "description": description}
    for key in CLAUDE_AGENT_KEYS:
        if key in meta:
            value = meta[key]
            front[key] = ", ".join(value) if key in ("tools", "disallowedTools") and isinstance(value, list) else value
    if skills:
        front["skills"] = skills
    return f"---\n{yaml_mapping(front)}---\n\n<!-- {note} -->\n\n{body}"


def render_codex_agent(agent, description, meta, body, note, plan) -> str:
    unknown_keys(agent, meta, CODEX_AGENT_KEYS, "codex", plan)
    lines = [f"# {note}", f"name = {toml_string(agent.name)}", f"description = {toml_string(description)}"]
    for key in CODEX_AGENT_KEYS:
        if key in meta:
            lines.append(f"{key} = {toml_value(meta[key])}")
    lines.append(f"developer_instructions = {toml_multiline(body)}")
    text = "\n".join(lines) + "\n"
    parsed = tomllib.loads(text)
    if parsed["developer_instructions"] != body or parsed["description"] != description:
        raise SyncError(f"{agent.label}: Codex TOML did not round-trip; report this as an engine defect")
    return text


def render_claude_skill(skill, description, meta, body, note, plan) -> str:
    unknown_keys(skill, meta, CLAUDE_SKILL_KEYS, "claude", plan)
    front = {"name": skill.name, "description": description}
    front.update({key: meta[key] for key in CLAUDE_SKILL_KEYS if key in meta})
    return f"---\n{yaml_mapping(front)}---\n\n{note}\n\n{body}"


def render_codex_skill(skill, description, meta, body, note, plan) -> tuple[bytes, bytes | None]:
    unknown_keys(skill, meta, CODEX_SKILL_KEYS, "codex", plan)
    front = {"name": skill.name, "description": description}
    if skill.meta.get("summary"):
        front["metadata"] = {"short-description": skill.meta["summary"]}
    openai = {}
    if "display_name" in meta:
        openai["interface"] = {"display_name": meta["display_name"]}
        if skill.meta.get("summary"):
            openai["interface"]["short_description"] = skill.meta["summary"]
    if "allow_implicit_invocation" in meta:
        openai["policy"] = {"allow_implicit_invocation": bool(meta["allow_implicit_invocation"])}
    skill_md = f"---\n{yaml_mapping(front)}---\n\n{note}\n\n{body}".encode()
    return skill_md, (yaml_mapping(openai).encode() if openai else None)


