def resolve_project(argument: str | None) -> Path:
    if argument:
        return Path(argument).resolve()
    own = Path(__file__).resolve()
    if own.parent.name == DELIVERY_DIR and own.name == "sync.py":
        return own.parent.parent
    return Path.cwd().resolve()


def require_templates(project: Path | None, lock: dict | None = None) -> Templates:
    root = find_templates(project, lock) if project else None
    if root is None:
        own = Path(__file__).resolve().parent.parent
        root = own if is_templates_root(own) else None
    if root is None:
        raise SyncError(
            f"templates not found; set {TEMPLATES_ENV} to the workspace templates folder, "
            "or run the engine from templates/delivery/sync.py"
        )
    return load_templates(root)


def cmd_install(args) -> int:
    project = Path(args.project).resolve()
    if not project.is_dir():
        raise SyncError(f"{project}: not a directory; create the project folder first")
    templates = require_templates(project)
    if project == templates.root or project.is_relative_to(templates.root):
        raise SyncError(f"{project}: is inside the templates folder; install into a project")
    tools = [tool.strip() for tool in args.tools.split(",") if tool.strip()]
    if not tools or any(tool not in TOOLS for tool in tools) or len(tools) != len(set(tools)):
        raise SyncError(f"--tools must be a duplicate-free, comma-separated subset of {','.join(TOOLS)}")
    name = args.name or project.name
    seeded = []
    for target, relative in templates.manifest.get("seeds", {}).items():
        path = inside(project, target)
        if path.exists():
            continue
        text = (templates.root / relative).read_text(encoding="utf-8")
        text = text.replace("{{project.name}}", name).replace("{{sync.tools}}", ", ".join(json.dumps(t) for t in tools))
        atomic_write(path, text.encode())
        seeded.append(target)
    outcome = run_sync(project, templates)
    print(f"{SYSTEM} {templates.version} installed into {project}")
    for target in seeded:
        print(f"  seed    {target}")
    print("\n".join(describe(outcome.changes)))
    report_tail(outcome)
    print(
        "\nNext:\n"
        f"  - Review {CONFIG_REL}: project name, commands, and which tools to generate.\n"
        "  - Start a new Claude Code or Codex session in the project folder. Directories created by this\n"
        "    install are only watched by sessions that start after it.\n"
        "  - Codex asks you to trust the project's SessionStart hook once: review it with /hooks.\n"
        f"  - Commit the generated files with the project; they let a clone work without the templates."
    )
    return 0


def cmd_sync(args) -> int:
    project = resolve_project(args.project)
    lock = load_lock(project)
    if lock is None:
        raise SyncError(f"{project}: {SYSTEM} is not installed; run install first")
    templates = require_templates(project, lock)
    outcome = run_sync(project, templates, dry_run=args.dry_run)
    heading = "would change" if args.dry_run else "changed"
    if outcome.changes:
        print(f"{SYSTEM} {outcome.previous_version} -> {outcome.version}: {heading} {len(outcome.changes)} file(s) in {project}")
        print("\n".join(describe(outcome.changes)))
    else:
        print(f"{SYSTEM} {outcome.version}: {project} is up to date")
    report_tail(outcome)
    return 0


def report_tail(outcome: Outcome) -> None:
    if outcome.backup:
        print(f"Hand edits were backed up to {outcome.backup}. Move lasting changes into {EXTENSIONS_REL}/.")
    for warning in outcome.warnings:
        print(f"warning: {warning}")


def report_interruption_checkpoint(project: Path) -> None:
    checkpoint = project / CHECKPOINT_REL
    if not checkpoint.is_file():
        return
    try:
        result = subprocess.run(
            [sys.executable, str(checkpoint), "status", "--hook"],
            cwd=project,
            capture_output=True,
            text=True,
            check=False,
            timeout=15,
        )
        if result.stdout:
            print(result.stdout, end="" if result.stdout.endswith("\n") else "\n")
        if result.returncode:
            detail = result.stderr.strip()
            suffix = f" ({detail})" if detail else ""
            print(f"{SYSTEM}: interruption checkpoint could not be read{suffix}; run "
                  f"python3 {CHECKPOINT_REL} status for details.")
    except (OSError, subprocess.TimeoutExpired) as error:
        print(f"{SYSTEM}: interruption checkpoint check failed: {error}.")


def cmd_session_start(args) -> int:
    if not sys.stdin.isatty():
        with contextlib.suppress(Exception):
            sys.stdin.read()
    project = None
    try:
        project = resolve_project(args.project)
        lock = load_lock(project)
        if lock is None:
            return 0
        root = find_templates(project, lock)
        if root is None:
            return 0  # a clone without the workspace: the committed files stand alone
        templates_engine = root / read_toml(root / "manifest.toml")["system"]["engine"]
        running = Path(__file__).resolve()
        if (templates_engine.resolve() != running and not os.environ.get(REEXEC_ENV)
                and templates_engine.is_file() and templates_engine.read_bytes() != running.read_bytes()):
            os.environ[REEXEC_ENV] = "1"
            os.execv(sys.executable, [sys.executable, str(templates_engine), "session-start",
                                      "--tool", args.tool, "--project", str(project)])
        templates = load_templates(root)
        outcome = run_sync(project, templates, adopt_pinned=False)
        version_pending = outcome.previous_version != outcome.version
        if not outcome.changes and not outcome.applied and not version_pending:
            return 0
        tool_def = templates.manifest["tools"][args.tool]
        if not outcome.applied:
            print(f"{SYSTEM}: template {outcome.previous_version} -> {outcome.version} has "
                  f"{len(outcome.changes)} pending file change(s), but this project is pinned. Adopt them with "
                  f"`python3 {ENGINE_REL} sync`.")
            return 0
        if not outcome.changes:
            return 0
        print(f"{SYSTEM}: synced the agent system from the workspace templates "
              f"({outcome.previous_version} -> {outcome.version}).")
        print("\n".join(describe(outcome.changes)))
        if any(change.target == tool_def["instructions"] for change in outcome.changes):
            print(f"{tool_def['instructions']} changed after this session loaded it. Read it again before "
                  "orchestrating delivery work.")
        report_tail(outcome)
    except SyncError as error:
        print(f"{SYSTEM}: sync skipped: {error}. Run `python3 {ENGINE_REL} status` for details.")
    except Exception as error:  # a session must never fail because of this hook
        print(f"{SYSTEM}: sync skipped after an unexpected {type(error).__name__}: {error}.")
    finally:
        if project is not None:
            report_interruption_checkpoint(project)
    return 0


def drift(project: Path, lock: dict) -> list[str]:
    edited = []
    for target, digest in lock.get("files", {}).items():
        path = inside(project, target)
        data = optional_bytes(path, target)
        if data is None:
            edited.append(f"{target} (missing)")
        elif sha256(data) != digest:
            edited.append(f"{target} (edited)")
    for target, digest in lock.get("blocks", {}).items():
        path = inside(project, target)
        block = current_block(optional_text(path, target))
        if block is None:
            edited.append(f"{target} (block missing)")
        elif sha256(block.encode()) != digest:
            edited.append(f"{target} (block edited)")
    return edited


def cmd_status(args) -> int:
    project = resolve_project(args.project)
    lock = load_lock(project)
    if lock is None:
        print(f"{project}: {SYSTEM} is not installed")
        return 1
    print(f"project      {project}")
    print(f"installed    {lock.get('version')} (synced {lock.get('synced_at')})")
    root = find_templates(project, lock)
    edited = drift(project, lock)
    if root is None:
        print("templates    not found; the committed files are in use unchanged")
    else:
        templates = load_templates(root)
        config = load_config(project, templates)
        print(f"templates    {templates.version} at {root}")
        print(f"mode         {config.mode}; tools: {', '.join(config.tools)}")
        outcome = run_sync(project, templates, dry_run=True)
        print(f"pending      {len(outcome.changes)} change(s)")
        print("\n".join(describe(outcome.changes)) or "", end="\n" if outcome.changes else "")
        for warning in outcome.warnings:
            print(f"warning      {warning}")
        local_agents, local_skills = load_local_components(project)
        if local_agents or local_skills:
            print("local        " + ", ".join(c.label for c in (*local_agents, *local_skills)))
    extensions = sorted(p.relative_to(project).as_posix() for p in (project / EXTENSIONS_REL).rglob("*.md")) \
        if (project / EXTENSIONS_REL).is_dir() else []
    if extensions:
        print("extensions   " + ", ".join(extensions))
    for item in edited:
        print(f"hand edit    {item}")
    return 0


def cmd_verify(args) -> int:
    project = resolve_project(args.project)
    problems, notes = [], []
    lock = load_lock(project)
    if lock is None:
        print(f"FAIL  {LOCK_REL}: missing; {SYSTEM} is not installed")
        return 1
    problems.extend(f"{item}: differs from what the sync wrote" for item in drift(project, lock))
    layout = lock.get("layout", {})
    for target in lock.get("files", {}):
        path = project / target
        if not path.is_file():
            continue
        parent = Path(target).parent.as_posix()
        is_agent = {tool: parent == dirs.get("agents_dir") for tool, dirs in layout.items()}
        if is_agent.get("codex"):
            try:
                parsed = tomllib.loads(path.read_text(encoding="utf-8"))
            except tomllib.TOMLDecodeError as error:
                problems.append(f"{target}: invalid TOML ({error})")
                continue
            if not all(parsed.get(key) for key in ("name", "description", "developer_instructions")):
                problems.append(f"{target}: a Codex agent needs name, description, and developer_instructions")
        if is_agent.get("claude") or path.name == "SKILL.md":
            text = path.read_text(encoding="utf-8")
            head = text.split("\n---\n", 1)[0]
            if not text.startswith("---\n") or "\nname: " not in head or "\ndescription: " not in head:
                problems.append(f"{target}: frontmatter needs name and description")
    for target in lock.get("hooks", []):
        path = project / target
        text = path.read_text(encoding="utf-8") if path.is_file() else ""
        if HOOK_MARKER not in text:
            problems.append(f"{target}: the SessionStart hook is not registered")
    root = find_templates(project, lock)
    if root is None:
        notes.append("templates not found: currency against the templates was not checked")
    else:
        templates = load_templates(root)
        try:
            outcome = run_sync(project, templates, dry_run=True)
        except SyncError as error:
            problems.append(str(error))
        else:
            problems.extend(f"{c.target}: out of date with templates {templates.version}" for c in outcome.changes)
            for warning in outcome.warnings:
                notes.append(warning)
            if lock.get("version") != templates.version:
                problems.append(f"{LOCK_REL}: records {lock.get('version')}, templates are {templates.version}")
    for note in notes:
        print(f"note: {note}")
    for problem in problems:
        print(f"FAIL  {problem}")
    print(f"{len(problems)} finding(s) in {project}")
    return 1 if problems else 0


def cmd_sync_all(args) -> int:
    root = Path(args.root).resolve()
    status = 0
    for project in sorted(p for p in root.iterdir() if (p / LOCK_REL).is_file()):
        try:
            templates = require_templates(project, load_lock(project))
            outcome = run_sync(project, templates, dry_run=args.dry_run)
            verb = "would change" if args.dry_run else "changed"
            print(f"{project.name}: {verb} {len(outcome.changes)} file(s)")
            print("\n".join(describe(outcome.changes)) or "", end="\n" if outcome.changes else "")
            report_tail(outcome)
        except SyncError as error:
            print(f"{project.name}: FAIL {error}")
            status = 1
    return status


