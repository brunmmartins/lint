class SyncError(Exception):
    """A problem that stops a sync before anything is written."""


# --------------------------------------------------------------------------------------------------
# Small utilities


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def utc_stamp() -> str:
    return dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")


def read_toml(path: Path) -> dict:
    try:
        return tomllib.loads(path.read_text(encoding="utf-8"))
    except OSError as error:
        raise SyncError(f"{path}: unreadable ({error.strerror})") from error
    except tomllib.TOMLDecodeError as error:
        raise SyncError(f"{path}: invalid TOML ({error})") from error


def atomic_write(path: Path, data: bytes, executable: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp-{os.getpid()}")
    temporary.write_bytes(data)
    if executable:
        temporary.chmod(0o755)
    os.replace(temporary, path)


def inside(root: Path, relative: str) -> Path:
    target = (root / relative).resolve()
    if not target.is_relative_to(root.resolve()):
        raise SyncError(f"{relative}: resolves outside {root}")
    return target


def normalize_text(text: str) -> str:
    text = re.sub(r"[ \t]+\n", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip("\n") + "\n"


def yaml_scalar(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return json.dumps(str(value), ensure_ascii=False)


def yaml_mapping(mapping: dict, indent: int = 0) -> str:
    lines, pad = [], " " * indent
    for key, value in mapping.items():
        if isinstance(value, dict):
            lines.append(f"{pad}{key}:")
            lines.append(yaml_mapping(value, indent + 2).rstrip("\n"))
        elif isinstance(value, list):
            lines.append(f"{pad}{key}:")
            lines.extend(f"{pad}  - {yaml_scalar(item)}" for item in value)
        else:
            lines.append(f"{pad}{key}: {yaml_scalar(value)}")
    return "\n".join(lines) + "\n"


def toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def toml_multiline(value: str) -> str:
    escaped = value.replace("\\", "\\\\")
    escaped = re.sub(r'"(?="")', '\\"', escaped)
    escaped = re.sub(r"[\x00-\x08\x0b-\x1f\x7f]", lambda m: f"\\u{ord(m.group(0)):04x}", escaped)
    return f'"""\n{escaped}"""'


def toml_value(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(item) for item in value) + "]"
    return toml_string(str(value))


def md_cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")

def require_mapping(value, where: str) -> dict:
    if not isinstance(value, dict):
        raise SyncError(f"{where}: expected a table")
    return value


def require_list(value, where: str) -> list:
    if not isinstance(value, list):
        raise SyncError(f"{where}: expected an array")
    return value


def template_source(root: Path, relative, where: str) -> Path:
    if not isinstance(relative, str) or not relative:
        raise SyncError(f"{where}: source must be a non-empty relative path")
    path = (root / relative).resolve()
    if not path.is_relative_to(root.resolve()):
        raise SyncError(f"{where}: source {relative!r} resolves outside {root}")
    return path


