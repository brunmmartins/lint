@dataclass
class Change:
    action: str  # "write", "delete"
    target: str
    kind: str  # "file", "block", "hook"
    content: bytes | None = None
    backup: bool = False
    detail: str = ""


def load_lock(project: Path) -> dict | None:
    path = project / LOCK_REL
    if not path.exists() and not path.is_symlink():
        return None
    if not path.is_file():
        raise SyncError(f"{LOCK_REL}: expected a regular file")
    try:
        lock = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
        raise SyncError(f"{LOCK_REL}: unreadable ({error})") from error
    if not isinstance(lock, dict) or lock.get("system") != SYSTEM:
        raise SyncError(f"{LOCK_REL}: not a {SYSTEM} lock")
    if lock.get("schema") != 1:
        raise SyncError(f"{LOCK_REL}: schema must be 1")
    for key in ("files", "blocks", "layout"):
        require_mapping(lock.get(key, {}), f"{LOCK_REL}: {key}")
    for key in ("tools", "hooks"):
        values = require_list(lock.get(key, []), f"{LOCK_REL}: {key}")
        if any(not isinstance(value, str) for value in values):
            raise SyncError(f"{LOCK_REL}: {key} must contain strings")
    for key in ("files", "blocks"):
        if any(not isinstance(target, str) or not isinstance(digest, str)
               for target, digest in lock.get(key, {}).items()):
            raise SyncError(f"{LOCK_REL}: {key} must map paths to hashes")
    if lock.get("source") is not None and not isinstance(lock["source"], str):
        raise SyncError(f"{LOCK_REL}: source must be a string")
    return lock


def replace_block(text: str | None, block: str | None) -> str | None:
    text = text or ""
    managed = f"{BLOCK_BEGIN}\n{block}{BLOCK_END}\n" if block is not None else ""
    if BLOCK_RE.search(text):
        updated = BLOCK_RE.sub(lambda _: managed, text, count=1)
    elif block is None:
        updated = text
    else:
        updated = managed if not text.strip() else text.rstrip("\n") + "\n\n" + managed
    if block is None and updated.strip():
        updated = updated.rstrip("\n") + "\n"
    return updated if updated.strip() else None


def current_block(text: str | None) -> str | None:
    matches = list(BLOCK_RE.finditer(text or ""))
    if len(matches) > 1:
        raise SyncError("instruction file contains more than one rust-delivery managed block")
    return matches[0].group(1) if matches else None


def merge_hook(text: str | None, command: str | None, target: str) -> str | None:
    try:
        data = json.loads(text) if text and text.strip() else {}
    except json.JSONDecodeError as error:
        raise SyncError(f"{target}: invalid JSON ({error}); fix it so the SessionStart hook can be registered") from error
    if not isinstance(data, dict):
        raise SyncError(f"{target}: expected a JSON object")
    hooks = require_mapping(data.get("hooks", {}), f"{target}: hooks")
    groups = require_list(hooks.get("SessionStart", []), f"{target}: hooks.SessionStart")

    validated = []
    ours = []
    for group_index, value in enumerate(groups, 1):
        group = require_mapping(value, f"{target}: SessionStart group {group_index}")
        handlers = require_list(group.get("hooks", []), f"{target}: SessionStart group {group_index} hooks")
        for handler_index, item in enumerate(handlers, 1):
            handler = require_mapping(
                item, f"{target}: SessionStart group {group_index} hook {handler_index}"
            )
            hook_text = str(handler.get("command", ""))
            if HOOK_MARKER in hook_text and "session-start" in hook_text:
                ours.append((group, handler))
        validated.append((group, handlers))

    desired = {"type": "command", "command": command, "timeout": HOOK_TIMEOUT} if command else None
    if desired and len(ours) == 1 and ours[0][1] == desired and ours[0][0].get("matcher") == HOOK_MATCHER:
        return text
    if not desired and not ours:
        return text
    kept = []
    for group, handlers in validated:
        remaining = [handler for handler in handlers if not any(handler is own for _, own in ours)]
        if remaining:
            kept.append({**group, "hooks": remaining})
    if desired:
        kept.append({"matcher": HOOK_MATCHER, "hooks": [desired]})
    if kept:
        hooks["SessionStart"] = kept
    else:
        hooks.pop("SessionStart", None)
    if hooks:
        data["hooks"] = hooks
    else:
        data.pop("hooks", None)
    if not data:
        return None
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def optional_bytes(path: Path, target: str) -> bytes | None:
    if not path.exists() and not path.is_symlink():
        return None
    if not path.is_file():
        raise SyncError(f"{target}: expected a regular file")
    try:
        return path.read_bytes()
    except OSError as error:
        raise SyncError(f"{target}: unreadable ({error})") from error


def optional_text(path: Path, target: str) -> str | None:
    data = optional_bytes(path, target)
    if data is None:
        return None
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError as error:
        raise SyncError(f"{target}: expected UTF-8 text ({error})") from error


def diff_plan(project: Path, plan: Plan, lock: dict | None) -> list[Change]:
    lock = lock or {}
    locked_files, locked_blocks = lock.get("files", {}), lock.get("blocks", {})
    changes: list[Change] = []
    for target, content in sorted(plan.files.items()):
        path = inside(project, target)
        current = optional_bytes(path, target)
        if current == content:
            continue
        edited = current is not None and sha256(current) != locked_files.get(target)
        changes.append(Change("write", target, "file", content, backup=edited,
                              detail="replaces a hand-edited or unmanaged file" if edited else ""))
    for target, digest in sorted(locked_files.items()):
        if target in plan.files:
            continue
        path = inside(project, target)
        current = optional_bytes(path, target)
        if current is not None:
            edited = sha256(current) != digest
            changes.append(Change("delete", target, "file", backup=edited, detail="no longer generated"))
    for target in sorted(set(plan.blocks) | set(locked_blocks)):
        path = inside(project, target)
        text = optional_text(path, target)
        block = plan.blocks.get(target)
        existing = current_block(text)
        if existing == block:
            continue
        updated = replace_block(text, block)
        if updated == text:
            continue
        edited = existing is not None and sha256(existing.encode()) != locked_blocks.get(target)
        action = "write" if updated is not None else "delete"
        changes.append(Change(action, target, "block", updated.encode() if updated is not None else None,
                              backup=edited, detail="orchestrator block"))
    hook_targets = set(plan.hooks) | set(lock.get("hooks", []))
    for target in sorted(hook_targets):
        path = inside(project, target)
        text = optional_text(path, target)
        tool = plan.hooks.get(target)
        updated = merge_hook(text, hook_command(tool) if tool else None, target)
        if updated == text:
            continue
        action = "write" if updated is not None else "delete"
        changes.append(Change(action, target, "hook", updated.encode() if updated is not None else None,
                              detail="SessionStart hook"))
    return changes


def apply_changes(project: Path, plan: Plan, changes: list[Change], templates: Templates, config: Config) -> str | None:
    stamp, backup_root = utc_stamp(), None
    for change in changes:
        path = inside(project, change.target)
        if change.backup and path.is_file():
            backup_root = project / BACKUPS_REL / stamp
            destination = backup_root / change.target
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, destination)
        if change.action == "write":
            atomic_write(path, change.content, executable=change.target == ENGINE_REL)
        elif path.is_file():
            path.unlink()
            prune_empty_dirs(project, path.parent)
    lock = {
        "schema": 1,
        "system": SYSTEM,
        "version": templates.version,
        "source": os.path.relpath(templates.root, project),
        "tools": config.tools,
        "files": {target: sha256(content) for target, content in sorted(plan.files.items())},
        "blocks": {target: sha256(block.encode()) for target, block in sorted(plan.blocks.items())},
        "hooks": sorted(plan.hooks),
        "layout": {tool: {key: templates.manifest["tools"][tool][key] for key in ("agents_dir", "skills_dir")}
                   for tool in config.tools},
        "synced_at": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
    }
    atomic_write(project / LOCK_REL, (json.dumps(lock, indent=2) + "\n").encode())
    return os.path.relpath(backup_root, project) if backup_root else None


def prune_empty_dirs(project: Path, directory: Path) -> None:
    stop = {project.resolve(), (project / DELIVERY_DIR).resolve()}
    while directory.resolve() not in stop and directory.is_dir() and not any(directory.iterdir()):
        directory.rmdir()
        directory = directory.parent


def lock_is_stale(lock: dict | None, plan: Plan, templates: Templates, config: Config) -> bool:
    if not lock:
        return True
    return (
        lock.get("version") != templates.version
        or lock.get("tools") != config.tools
        or set(lock.get("files", {})) != set(plan.files)
        or set(lock.get("blocks", {})) != set(plan.blocks)
        or set(lock.get("hooks", [])) != set(plan.hooks)
        or any(lock["files"].get(t) != sha256(c) for t, c in plan.files.items())
        or any(lock["blocks"].get(t) != sha256(b.encode()) for t, b in plan.blocks.items())
    )


@contextlib.contextmanager
def project_mutex(project: Path):
    path = project / MUTEX_REL
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "a+") as handle:
        try:
            import fcntl
        except ImportError:  # Windows without WSL: no advisory locks; syncs rarely overlap
            yield
            return
        deadline = time.monotonic() + 20
        while True:
            try:
                fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
                break
            except BlockingIOError:
                if time.monotonic() > deadline:
                    raise SyncError(f"another sync holds {MUTEX_REL}") from None
                time.sleep(0.1)
        try:
            yield
        finally:
            fcntl.flock(handle, fcntl.LOCK_UN)


@dataclass
class Outcome:
    changes: list[Change]
    warnings: list[str]
    backup: str | None
    applied: bool
    previous_version: str | None
    version: str


def run_sync(project: Path, templates: Templates, dry_run: bool = False, adopt_pinned: bool = True) -> Outcome:
    with project_mutex(project):
        lock = load_lock(project)
        config = load_config(project, templates)
        plan = build_plan(project, templates, config)
        changes = diff_plan(project, plan, lock)
        stale = lock_is_stale(lock, plan, templates, config)
        apply = not dry_run and (adopt_pinned or config.mode == "auto") and (changes or stale)
        backup = apply_changes(project, plan, changes, templates, config) if apply else None
        return Outcome(changes, plan.warnings, backup, bool(apply), (lock or {}).get("version"), templates.version)


def describe(changes: list[Change]) -> list[str]:
    lines = []
    for change in changes:
        verb = {"write": "update", "delete": "remove"}[change.action]
        extra = f" ({change.detail})" if change.detail else ""
        lines.append(f"  {verb:<7} {change.target}{extra}")
    return lines


