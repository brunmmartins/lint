#!/usr/bin/env python3
"""Sync the rust-delivery agent system (agents, skills, orchestrator) into a Rust project.

The workspace `templates/` folder is the only source. This engine renders it for Claude Code and Codex,
applies the project's own configuration and extensions, and keeps the result current.

Commands:
  check                        validate the templates themselves
  install PROJECT [--tools claude,codex] [--name NAME]
                               seed .delivery/, render everything, register the SessionStart hooks
  sync [PROJECT] [--dry-run]   render from the templates now (also adopts updates in pinned mode)
  session-start --tool TOOL    SessionStart hook entry point: quiet when nothing changed, never fails
  status [PROJECT]             installed and available versions, pending changes, hand edits
  verify [PROJECT]             exit 1 unless the installation is complete, unedited, and current
  sync-all ROOT [--dry-run]    sync every installed project directly under ROOT
  new agent|skill NAME [PROJECT]
                               scaffold a project-local component in .delivery/local/

PROJECT defaults to the project that contains this copy of the engine, or else the current directory.
Exit status: 0 on success, 1 on findings or errors, 2 on bad usage. Needs Python 3.11 or newer, and
nothing outside the standard library.
"""

