def cmd_check(args) -> int:
    root = Path(args.templates).resolve() if args.templates else Path(__file__).resolve().parent.parent
    problems, notes = [], []
    try:
        templates = load_templates(root)
    except SyncError as error:
        print(f"FAIL  {error}")
        return 1
    listed_agents = {c.source.resolve() for c in templates.agents}
    listed_skills = {c.source.resolve() for c in templates.skills}
    delivery = templates.engine.parent
    for path in sorted((delivery / "agents").glob("*.md")):
        if path.resolve() not in listed_agents:
            problems.append(f"{path.relative_to(root)}: agent source is not listed in manifest.toml")
    for path in sorted((delivery / "skills").glob("*/SKILL.md")):
        if path.parent.resolve() not in listed_skills:
            problems.append(f"{path.parent.relative_to(root)}: skill source is not listed in manifest.toml")
    registered_partials = {
        (root / relative).resolve() for relative in templates.manifest.get("partials", {}).values()
    }
    for path in sorted((delivery / "partials").glob("*")):
        if path.is_file() and path.resolve() not in registered_partials:
            problems.append(f"{path.relative_to(root)}: partial source is not listed in manifest.toml")
    registered_project_files = {
        (root / relative).resolve()
        for table in ("seeds", "managed")
        for relative in templates.manifest.get(table, {}).values()
    }
    for path in sorted((delivery / "project").glob("*")):
        if path.is_file() and path.resolve() not in registered_project_files:
            problems.append(f"{path.relative_to(root)}: project source is not listed in manifest.toml")
    orchestrator_source = (root / templates.manifest["orchestrator"]["source"]).resolve()
    for path in sorted((delivery / "orchestrator").glob("*.md")):
        if path.resolve() != orchestrator_source:
            problems.append(f"{path.relative_to(root)}: orchestrator source is not listed in manifest.toml")
    skill_names = {skill.name for skill in templates.skills}
    for agent in templates.agents:
        for name in agent.meta.get("skills", []):
            if name not in skill_names:
                problems.append(f"agent {agent.name}: skill {name!r} is not in the manifest")
        if not agent.meta.get("stage"):
            problems.append(f"agent {agent.name}: frontmatter needs a stage")
    for component in (*templates.agents, *templates.skills):
        if not component.meta.get("summary"):
            problems.append(f"{component.label}: frontmatter needs a one-line summary for the orchestrator roster")
    for component in (*templates.agents, *templates.skills):
        if "{{project_extensions}}" not in component.body:
            notes.append(f"{component.label}: no {{{{project_extensions}}}} slot; extensions will be appended at the end")
    if "{{project_extensions}}" not in templates.orchestrator:
        problems.append("orchestrator: needs a {{project_extensions}} slot")
    with tempfile.TemporaryDirectory(prefix="rust-delivery-check-") as directory:
        scratch = Path(directory)
        try:
            check_render(scratch, templates, problems, notes)
        except SyncError as error:
            problems.append(str(error))
    for note in notes:
        print(f"note: {note}")
    for problem in problems:
        print(f"FAIL  {problem}")
    print(f"{len(problems)} finding(s) in {root}")
    return 1 if problems else 0


def check_render(scratch: Path, templates: Templates, problems: list[str], notes: list[str]) -> None:
    """Render every component for every tool into an empty project with default configuration."""
    config = load_config(scratch, templates)
    plan = build_plan(scratch, templates, config)
    notes.extend(plan.warnings)
    for tool in TOOLS:
        tool_def = templates.manifest["tools"][tool]
        size = len(plan.blocks[tool_def["instructions"]].encode())
        notes.append(f"{tool_def['instructions']}: orchestrator block is {size} bytes")
    rendered = {**plan.files, **{target: block.encode() for target, block in plan.blocks.items()}}
    verbatim = set(templates.manifest.get("managed", {})) | {ENGINE_REL}
    leftovers = [t for t, c in rendered.items()
                 if t not in verbatim and t.endswith((".md", ".toml")) and re.search(rb"\{\{|\}\}", c)]
    problems.extend(f"{target}: rendered output still contains {{{{ or }}}}" for target in leftovers)
    print(f"rendered {len(plan.files)} files and {len(plan.blocks)} instruction blocks for {', '.join(TOOLS)}")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="sync.py", description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)
    check = sub.add_parser("check", help="validate the templates")
    check.add_argument("--templates", help="templates folder (default: the one containing this engine)")
    install = sub.add_parser("install", help="install into a project")
    install.add_argument("project")
    install.add_argument("--tools", default="claude,codex")
    install.add_argument("--name", help="project name for .delivery/project.toml (default: folder name)")
    sync = sub.add_parser("sync", help="render from the templates now")
    sync.add_argument("project", nargs="?")
    sync.add_argument("--dry-run", action="store_true")
    start = sub.add_parser("session-start", help="SessionStart hook entry point")
    start.add_argument("--tool", choices=TOOLS, required=True)
    start.add_argument("--project")
    status = sub.add_parser("status", help="show installation state")
    status.add_argument("project", nargs="?")
    verify = sub.add_parser("verify", help="fail unless installed, unedited, and current")
    verify.add_argument("project", nargs="?")
    sync_all = sub.add_parser("sync-all", help="sync every installed project under ROOT")
    sync_all.add_argument("root")
    sync_all.add_argument("--dry-run", action="store_true")
    new = sub.add_parser("new", help="scaffold a project-local agent or skill")
    new.add_argument("kind", choices=("agent", "skill"))
    new.add_argument("name")
    new.add_argument("project", nargs="?")
    args = parser.parse_args(argv)
    handlers = {
        "check": cmd_check, "install": cmd_install, "sync": cmd_sync, "session-start": cmd_session_start,
        "status": cmd_status, "verify": cmd_verify, "sync-all": cmd_sync_all, "new": cmd_new,
    }
    try:
        return handlers[args.command](args)
    except SyncError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
