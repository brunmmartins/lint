def hook_command(tool: str) -> str:
    """The SessionStart command for one tool.

    Hooks run in the session's working directory, which may be below the project root, and Codex has no
    project-dir variable. So the command walks up to the nearest installed engine and does nothing when
    there is none. It must stay byte-identical across releases: Codex asks the user to trust a hook
    again whenever its hash changes.
    """
    return (
        "python3 -c \"import pathlib,runpy,sys; c=pathlib.Path.cwd(); "
        "e=next((d/'.delivery/sync.py' for d in (c,*c.parents) if (d/'.delivery/sync.py').is_file()),None); "
        f"sys.argv=['sync.py','session-start','--tool','{tool}']; "
        "e and runpy.run_path(str(e),run_name='__main__')\""
    )


